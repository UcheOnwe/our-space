/**
 * Gamezop-specific launch/artwork URL construction — the ONE file that
 * knows anything about Gamezop's own domains/paths. Presentation
 * components (GameCard, GamePlayer, GameSelector) never see these
 * constants; they go through launch.ts's `resolveGameLaunchUrl`, which
 * dispatches by `Game.provider`. When Gamezop's publisher API/contract
 * arrives, this file is what gets replaced (a real SDK/signed-URL call
 * instead of a static public path) — nothing else in the Gaming feature
 * needs to change.
 *
 * Both URLs below are Gamezop's OWN publicly-documented, no-credential
 * embed mechanism — copied directly from the "Embed" tab Gamezop's own
 * business.gamezop.com catalog page shows for each game (e.g.
 * https://business.gamezop.com/html5-games/Ludo-With-Friends/SkhljT2fdgb),
 * not reverse-engineered or guessed. `zv1y2i8p` is Gamezop's own shared
 * PUBLIC/evaluation subdomain — every game's public embed snippet on
 * that page uses this exact same subdomain, it isn't specific to Our
 * Space or generated by us.
 *
 * IMPORTANT — confirmed directly on the live game page: it displays its
 * own notice, "This demo-only environment is provided for evaluation
 * purposes. Use in products, public settings, or for commercial purposes
 * is prohibited." This integration is for internal proof-of-concept
 * evaluation only, while Gamezop's publisher application is pending —
 * see the Gaming POC's own report for the full context. Do not treat
 * this as production-ready for real end users until real publisher
 * credentials replace it.
 */
const GAMEZOP_PUBLIC_EMBED_ORIGIN = 'https://zv1y2i8p.play.gamezop.com'

export function buildGamezopLaunchUrl(providerGameId: string): string {
  return `${GAMEZOP_PUBLIC_EMBED_ORIGIN}/g/${providerGameId}`
}

/** Gamezop's own publicly-served cover image for this exact game — the
 * same image their business.gamezop.com catalog page itself displays,
 * not a separately-hosted or generated asset. */
export function buildGamezopArtworkUrl(providerGameId: string): string {
  return `https://business.gamezop.com/img/gamezop/${providerGameId}/cover.jpg?w=600&q=50`
}
